'use strict';
/* Run: node hexategos-pruebas/game/tests/smoke-0391-landcover.mjs */
import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const source=read('data/geo-landcover-0391.js');
const win={};new Function('window',source)(win);
const mod=win.HexategosLandCover0391;
assert.equal(mod.types.length,17);
const cover=(lat,lon,biome='mediterranean',tier=0)=>mod.types[mod.classify(lat,lon,biome,tier)]?.id;
assert.equal(mod.classify(40,-5,'sea',0),-1);
assert.equal(cover(76,-43,'ice'),'ice');
assert.equal(cover(36,-5,'mediterranean',3),'rock');
assert.equal(cover(41.65,-4.72),'crops');
assert.equal(cover(38.88,-6.97),'dehesa');
assert.equal(cover(43.361,-5.859),'deciduous');
assert.equal(cover(36.96,-6.47),'wetland');
assert.equal(cover(40.72,.72),'wetland');
assert.equal(mod.classify(40,-5,'plain',0),mod.classify(40,-5,'plain',0));
const types=new Set();
for(let y=36;y<44;y+=.2)for(let x=-9;x<3;x+=.2)types.add(mod.classify(y,x,'mediterranean'));
assert.ok(types.size>=9,'several coherent categories coexist in Iberia');
const overlay=fs.readFileSync(new URL('../../../hexategos-atlas/atlas-landcover-0391.js',import.meta.url),'utf8');
const html=fs.readFileSync(new URL('../../../hexategos-atlas/index.html',import.meta.url),'utf8');
const ui=fs.readFileSync(new URL('../../../hexategos-atlas/atlas-ui.js',import.meta.url),'utf8');
assert.ok(html.includes('id="cover"')&&html.includes('id="coverLegend"'));
assert.ok(html.indexOf('geo-landcover-0391.js')<html.indexOf('atlas-landcover-0391.js'));
assert.ok(html.indexOf('atlas-landcover-0391.js')<html.indexOf('atlas-ui.js'));
assert.ok(ui.includes('HexategosAtlasLandCover0391?.cellInfo(i)'));
assert.ok(overlay.includes('Uint8Array(L.n)'),'one-byte caches instead of full per-cell objects');
assert.ok(!/setInterval\s*\(/.test(overlay),'no new per-system timers');
new Function(overlay);
console.log('HEXATEGOS ATLAS 0.39.1 land cover: OK');
