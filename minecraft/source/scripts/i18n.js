const STORAGE_KEY = 'minecraftjs_language';
export const supportedLanguages = Object.keys(MESSAGES);

function getInitialLanguage() {
  let stored;
  try { stored = localStorage.getItem(STORAGE_KEY); } catch { /* private mode */ }
  if (supportedLanguages.includes(stored)) return stored;
  const browserLanguage = navigator.language?.slice(0, 2).toLowerCase();
  return supportedLanguages.includes(browserLanguage) ? browserLanguage : 'es';
}

let currentLanguage = getInitialLanguage();
const listeners = new Set();

export function t(key) {
  return MESSAGES[currentLanguage][key] ?? MESSAGES.es[key] ?? key;
}

export function getLanguage() { return currentLanguage; }

export function setLanguage(language) {
  if (!supportedLanguages.includes(language)) return;
  currentLanguage = language;
  try { localStorage.setItem(STORAGE_KEY, language); } catch { /* optional setting */ }
  document.documentElement.lang = language;
  document.title = t('documentTitle');
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((element) => {
    const label = t(element.dataset.i18nTitle);
    element.title = label;
    element.setAttribute('aria-label', label);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nAria));
  });
  document.getElementById('language-select').value = language;
  listeners.forEach((fn) => fn());
}

export function onLanguageChange(callback) {
  listeners.add(callback);
  return () => listeners.delete(callback);
}
